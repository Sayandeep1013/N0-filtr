/**
 * Writes a finished figure two ways:
 *
 *   · `components/figures/generated/<name>.svg.ts` — the static SVG as a string,
 *     imported only by the server component, so it never ships as JavaScript.
 *   · `components/figures/generated/<name>.live.ts` — the handful of numbers the
 *     client needs to move it.
 *   · `tools/figures/out/<name>.html` — a standalone preview for the anatomy
 *     skill's capture and line-end scripts.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { k } from './parts.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');

export function emit(name, { svg, live, title, hint, readout }) {
  /* Two files, so the client's import of the numbers can never drag the SVG
     string into a bundle with it. */
  const dir = join(ROOT, 'components', 'figures', 'generated');
  mkdirSync(dir, { recursive: true });
  const head = `/* Generated by tools/figures/${name}.mjs — do not edit. Rebuild with \`npm run figures\`. */\n`;
  writeFileSync(join(dir, `${name}.svg.ts`), `${head}export const SVG = ${JSON.stringify(svg)};\n`);
  writeFileSync(join(dir, `${name}.live.ts`), `${head}export const LIVE = ${JSON.stringify(live, null, 2)} as const;\n`);

  const css = readFileSync(join(ROOT, 'components', 'figures', 'iso.css'), 'utf8');
  const outHtml = join(HERE, 'out', `${name}.html`);
  mkdirSync(dirname(outHtml), { recursive: true });
  const body = k.plateHtml({ fig: 'Fig 01', title, hint, readout, body: `<div class="iso-stage">${svg}</div>` });
  writeFileSync(
    outHtml,
    `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${title}</title>` +
      `<style>${css}body{margin:0;background:#212121;color:#efefef;font:14px/1.6 ui-monospace,monospace}.iso-page{width:min(1100px,100% - 32px);margin:48px auto}.iso-plate{position:relative;padding:52px 24px;background:var(--anatomy-card);box-shadow:0 0 0 1px #ffffff4d}.iso-plate-corners{position:absolute;inset:18px 20px}.iso-plate-corner{position:absolute;font-size:11px;color:#737373;letter-spacing:.06em}[data-corner=fig]{top:0;left:0}[data-corner=title]{top:0;right:0;text-transform:uppercase}[data-corner=hint]{bottom:0;left:0;text-transform:uppercase}[data-corner=readout]{bottom:0;right:0}</style>` +
      `</head><body class="iso nf-fig"><main class="iso-page">${body}</main></body></html>`,
  );
  console.log(`wrote ${name}: svg ${(svg.length / 1024).toFixed(1)} KB`);
}
